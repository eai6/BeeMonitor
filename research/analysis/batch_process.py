def is_already_processed(video_path: Path, output_folder: Path) -> bool:
    """Check if a video has already been processed by looking for ANY output file."""
    video_stem = video_path.stem

    patterns = [
        f"{video_stem}_events.csv",
        f"{video_stem}_tracking*.csv",
        f"synthesized_{video_stem}*.mp4",
        f"{video_stem}_annotated.mp4",
    ]

    for pattern in patterns:
        if any(output_folder.glob(pattern)):
            return True

    return False


def process_video(monitor: BeeMonitor, video_path: Path, output_folder: Path):
    """Process a single video with two-mode tracking."""
    try:
        result = monitor.analyze_video(
            str(video_path),
            output_folder=str(output_folder),
            visualize=False,
            detection_mode="yolo_only",
        )
        return video_path, result
    except Exception as e:
        print(f"  ✗ Error processing {video_path.name}: {e}")
        import traceback
        traceback.print_exc()
        return video_path, None


def resolve_videos(input_folder: Path, video_load_list, video_extensions):
    """Return list[Path] of videos to consider, either from disk scan or from explicit list."""
    if video_load_list:
        # Convert filenames to Paths under input_folder
        wanted = [input_folder / name for name in video_load_list]

        missing = [p for p in wanted if not p.exists()]
        if missing:
            print("\n✗ Some video_load files were not found under input_folder:")
            for p in missing[:50]:
                print(f"   - {p}")
            if len(missing) > 50:
                print(f"   ... and {len(missing) - 50} more")
            sys.exit(1)

        # Optional sanity check: extension
        bad_ext = [p for p in wanted if p.suffix not in video_extensions]
        if bad_ext:
            print("\n⚠ Warning: Some video_load files have unsupported extensions and will be skipped:")
            for p in bad_ext:
                print(f"   - {p.name}")
            wanted = [p for p in wanted if p.suffix in video_extensions]

        return wanted

    # Otherwise scan folder
    return [p for p in input_folder.iterdir() if p.is_file() and p.suffix in video_extensions]


